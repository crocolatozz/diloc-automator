function renderIcon(name, options = {}) {
  const inner = PMR_ICON_PATHS[name] || '';
  const size = Number(options.size) || 15;
  const baseClass = options.className ? `svg-icon ${options.className}` : 'svg-icon';
  const ariaHidden = options.ariaHidden !== false ? ' aria-hidden="true"' : '';
  return `<svg class="${baseClass}" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round"${ariaHidden}>${inner}</svg>`;
}

function createSvgElement(name, options = {}) {
  const template = document.createElement('template');
  template.innerHTML = renderIcon(name, options).trim();
  return template.content.firstElementChild;
}

function hydrateDataIcons(root = document) {
  const placeholders = root.querySelectorAll('[data-icon]');
  placeholders.forEach((el) => {
    const name = el.getAttribute('data-icon');
    const className = el.getAttribute('data-icon-class') || '';
    const size = Number(el.getAttribute('data-icon-size')) || 15;
    const svgEl = createSvgElement(name, { className, size });
    if (svgEl) {
      el.replaceWith(svgEl);
    }
  });
}
